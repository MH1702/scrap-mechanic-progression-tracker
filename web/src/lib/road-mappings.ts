export function mappedTileRoads(name: string): RoadMapping | undefined {
  if (/^RuinCity_512_01(?:_NEW)?$/i.test(name)) return scrapCityRoads
  if (/^(?:Minidungeon_OverworldEntrance_Chemical_512_01|SiloDistrict_512_01)$/i.test(name)) {
    return siloDistrictRoads
  }
  if (/^Warehouse_Exterior_2Floors_256_01(?:_NEW)?$/i.test(name)) {
    return warehouse2Floor01Roads
  }
  if (/^Warehouse_Exterior_2Floors_256_02(?:_NEW)?$/i.test(name)) {
    return warehouse2Floor02Roads
  }
  if (/^Warehouse_Exterior_2Floors_256_03(?:_NEW)?$/i.test(name)) {
    return warehouse2Floor03Roads
  }
  if (/^Warehouse_Exterior_2Floors_256_04(?:_NEW)?$/i.test(name)) {
    return warehouse2Floor04Roads
  }
  if (/^Warehouse_Exterior_3Floors_256_01(?:_NEW)?$/i.test(name)) {
    return warehouse3Floor01Roads
  }
  if (/^Warehouse_Exterior_4Floors_256_(?:01(?:_NEW)?|Quest)$/i.test(name)) {
    return warehouse4Floor01Roads
  }
  return undefined
}

export function rotateRoadPoint(
  [x, y]: RoadPoint,
  rotation: number,
  size: number,
): RoadPoint {
  if (rotation === 1) return [y, size - x]
  if (rotation === 2) return [size - x, size - y]
  if (rotation === 3) return [size - y, x]
  return [x, y]
}
